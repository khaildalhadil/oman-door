import { asset } from './content'

export type StationId = 'nav' | 'sumhuram' | 'turtles' | 'ivory' | 'clothing'

export interface InfoItem {
  key: string // matches the Blender empty "Item_<key>"
  title: string
  text: string
  icon: string
  /** short extra line shown under the text (e.g. a note that is not from the encyclopedia) */
  note?: string
  /** encyclopedia reference shown under this card (e.g. «الموسوعة العُمانية، المجلد 3، ص 1129») */
  ref?: string
  /** recorded narration (URL or data: URL) played with the card */
  audio?: string
}

export interface TFQuestion {
  text: string
  answer: boolean
  explain: string
}

/** «اكتشفي الشخصية / المكان / الكائن» — shown when the student arrives */
export interface Riddle {
  kicker: string
  text: string
  question: string
  options: string[]
  answer: number
  /** shown after the right answer */
  reveal: { title: string; subtitle: string }
}

/** «تحدي المستكشف» — one or more steps */
export type ChallengeStep =
  | { kind: 'order'; prompt: string; items: string[] /* correct order */; success: string }
  | { kind: 'match'; prompt: string; pairs: [string, string][]; success: string }
  | { kind: 'choice'; prompt: string; options: string[]; answer: number; success: string }
  | { kind: 'multi'; prompt: string; options: string[]; answers: number[]; success: string }
  | { kind: 'tf'; questions: TFQuestion[] }

export interface StationDef {
  id: StationId
  title: string
  /** shorter title for signs, lists and the mission card */
  short: string
  subtitle: string
  color: string
  stampLabel: string
  intro: string
  riddle?: Riddle
  activityTitle: string
  activityHint: string
  model: string
  colliders: string
  items: InfoItem[]
  /** extra cards revealed by the activity (artifacts, clothing pieces, manuscripts) */
  extras?: InfoItem[]
  challenge: ChallengeStep[]
  /** «اكتشفي معلومة» 💡 — opens like a small card after the challenge */
  fact?: { title: string; lines: string[] }
  /** المرجع 📚 */
  ref?: string
  /** content still waiting for the encyclopedia article */
  pending?: string
  /** narration played when the station opens (with the riddle) */
  introAudio?: string
  /** closing words shown (and played) before the stamp */
  outro?: { text: string; audio?: string }
}

